# Compiles shaders\*.hlsl for SDL3 GPU (Direct3D 12 backend) and embeds the
# bytecode in uGPUShaders.pas, so the program needs no shader files at run time.
#   DXIL (Shader Model 6.0) with dxc.exe  - preferred by SDL3 on D3D12
#   DXBC (Shader Model 5.1) with fxc.exe  - fallback
# Both compilers ship with the Windows 10/11 SDK. Run after editing a shader:
#   powershell -ExecutionPolicy Bypass -File build_shaders.ps1

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$src = Join-Path $root 'shaders'
$out = Join-Path $src 'bin'
New-Item -ItemType Directory -Force $out | Out-Null

$kits = 'C:\Program Files (x86)\Windows Kits\10\bin'
$sdk = Get-ChildItem $kits -Directory | Where-Object { Test-Path (Join-Path $_.FullName 'x64\dxc.exe') } |
    Sort-Object { [version]$_.Name } | Select-Object -Last 1
if (-not $sdk) { throw "dxc.exe not found under $kits - install the Windows SDK" }
$dxc = Join-Path $sdk.FullName 'x64\dxc.exe'
$fxc = Join-Path $sdk.FullName 'x64\fxc.exe'
Write-Host "dxc: $dxc"

# name, file, stage
$shaders = @(
    @('FullscreenVS', 'fullscreen_vs.hlsl', 'vs'),
    @('DotsPS',       'dots_ps.hlsl',       'ps'),
    @('CompositePS',  'composite_ps.hlsl',  'ps'),
    @('OverlayPS',    'overlay_ps.hlsl',    'ps'),
    @('ParticlesVS',  'particles_vs.hlsl',  'vs'),
    @('ParticlesPS',  'particles_ps.hlsl',  'ps')
)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('unit uGPUShaders;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('{ GENERATED by build_shaders.ps1 from shaders\*.hlsl - do not edit.')
[void]$sb.AppendLine('  DXIL = dxc Shader Model 6.0, DXBC = fxc Shader Model 5.1. }')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('{$mode objfpc}{$H+}')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('interface')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('const')

foreach ($s in $shaders) {
    $name, $file, $stage = $s
    $hlsl = Join-Path $src $file
    foreach ($fmt in @('DXIL', 'DXBC')) {
        $bin = Join-Path $out "$name.$($fmt.ToLower())"
        if ($fmt -eq 'DXIL') {
            & $dxc -nologo -T "$($stage)_6_0" -E main -O3 -Fo $bin $hlsl
        } else {
            & $fxc /nologo /T "$($stage)_5_1" /E main /O3 /Fo $bin $hlsl | Out-Null
        }
        if ($LASTEXITCODE -ne 0) { throw "compiling $file ($fmt) failed" }
        $bytes = [IO.File]::ReadAllBytes($bin)
        [void]$sb.AppendLine("  $($name)_$($fmt): array[0..$($bytes.Length - 1)] of Byte = (")
        for ($i = 0; $i -lt $bytes.Length; $i += 24) {
            $n = [Math]::Min(24, $bytes.Length - $i)
            $line = ($bytes[$i..($i + $n - 1)] | ForEach-Object { '${0:X2}' -f $_ }) -join ','
            if ($i + $n -lt $bytes.Length) { $line += ',' } else { $line += ');' }
            [void]$sb.AppendLine("    $line")
        }
        Write-Host ("{0,-14} {1}  {2,6} bytes" -f $name, $fmt, $bytes.Length)
    }
}

[void]$sb.AppendLine('')
[void]$sb.AppendLine('implementation')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('end.')
[IO.File]::WriteAllText((Join-Path $root 'uGPUShaders.pas'), $sb.ToString())
Write-Host 'uGPUShaders.pas written'
